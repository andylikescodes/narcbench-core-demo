#!/usr/bin/env python3
"""Cross-model tables for the J-space separability analysis → results/jspace/CROSS_MODEL_TABLES.md.

Reads results/jspace/<model>/summary.json for the official models and results/jspace/gemma2_9b_frozen/frozen_stats.json
for the frozen Gemma numbers. The prose reading lives in results/jspace/RESULTS.md, written by hand from these tables.

  python3 scripts/jspace_cross_model.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABEL = {"qwen3_32b": "Qwen3-32B", "deepseek_r1_32b": "DeepSeek-R1-32B", "gpt_oss_20b": "GPT-OSS-20B",
         "qwen3_32b_gamma": "Qwen3-32B (γ-scaled frames, E1)", "deepseek_r1_32b_gamma": "DeepSeek-R1-32B (γ-scaled frames, E1)",
         "gpt_oss_20b_gamma": "GPT-OSS-20B (γ-scaled frames, E1)"}
K = "25"


def f3(x) -> str:
    try:
        return f"{float(x):.3f}"
    except (TypeError, ValueError):
        return "—"


def ci(a) -> str:
    return f"{f3(a['est'])} [{f3(a['ci'][0])}, {f3(a['ci'][1])}]"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="+", default=["qwen3_32b", "deepseek_r1_32b", "gpt_oss_20b"])
    ap.add_argument("--out", type=Path, default=ROOT / "results/jspace/CROSS_MODEL_TABLES.md")
    args = ap.parse_args()
    res = {m: json.loads((ROOT / "results/jspace" / m / "summary.json").read_text()) for m in args.models
           if (ROOT / "results/jspace" / m / "summary.json").exists()}
    fz_p = ROOT / "results/jspace/gemma2_9b_frozen/frozen_stats.json"
    fz = json.loads(fz_p.read_text()) if fz_p.exists() else None

    L = ["# J-space separability — cross-model tables", "",
         "Generated by `scripts/jspace_cross_model.py` from `results/jspace/<model>/summary.json` (design: `docs/jspace/JSPACE_SEPARABILITY_DESIGN.md`). "
         "Primary AUROC = mean of Peak, Split and Asymmetry episode AUROCs, band mean over the cached layers. Intervals: 95% bootstrap over episodes "
         "(stratified by family and mode, B = 2000); p: permutation of episode labels within family (B = 2000), one-sided above chance. "
         "Gemma-2-9B rows are the frozen 1 Oct numbers with Hanley–McNeil intervals (`results/jspace/gemma2_9b_frozen/`).", ""]

    L += ["## 1. Core discussion → Transfer final at k = 25 (A2)", "",
          "| model | n Transfer episodes | full | J-only | complement of J | random 25-dim subspace | another activation's frame | PCA k=25 | contrast k=25 | p(J > chance) | p(random > chance) |",
          "|---|---:|---|---|---|---|---|---|---|---:|---:|"]
    for m, s in res.items():
        a = s["A2_inference"][K]["arms"]
        L.append(f"| {LABEL.get(m, m)} | {s['A2_inference'][K]['n_episodes']} | {ci(a['full'])} | {ci(a['J'])} | {ci(a['C_J'])} | {ci(a['randsub'])} | {ci(a['shuffled'])} | {ci(a['pca'])} | {ci(a['contrast'])} | {a['J']['p_perm']:.3f} | {a['randsub']['p_perm']:.3f} |")
    if fz:
        t = fz["transfer_arms"]
        def g(name):
            p = t[name]["primary"]; return f"{f3(p['auroc'])} [{f3(p['ci95'][0])}, {f3(p['ci95'][1])}]"
        L.append(f"| Gemma-2-9B (frozen, W_U frames) | 72 | {g('full')} | {g('W_U k25 J-only')} | {g('W_U k25 complement')} | — | — | — | — | {t['W_U k25 J-only']['primary']['p_two_sided']:.3f} (two-sided, normal approx.) | — |")
        L.append(f"| Gemma-2-9B (frozen, Jacobian frames) | 72 | {g('full')} | {g('jac k25 J-only')} | {g('jac k25 complement')} | — | — | — | — | {t['jac k25 J-only']['primary']['p_two_sided']:.3f} (two-sided, normal approx.) | — |")

    L += ["", "### Paired differences at k = 25 (bootstrap over the same episodes)", "",
          "| model | complement − J | J − random subspace | J − another activation's frame | J − random unembedding rows | J − PCA | complement − full | complement of random − full | contrast − J |",
          "|---|---|---|---|---|---|---|---|---|"]
    for m, s in res.items():
        d = s["A2_inference"][K]["differences"]
        def dd(name):
            v = d.get(name); return f"{v['est']:+.3f} [{v['ci'][0]:+.3f}, {v['ci'][1]:+.3f}]" if v else "—"
        L.append(f"| {LABEL.get(m, m)} | {dd('C_J-J')} | {dd('J-randsub')} | {dd('J-shuffled')} | {dd('J-randrows')} | {dd('J-pca')} | {dd('C_J-full')} | {dd('C_randsub-full')} | {dd('contrast-J')} |")
    if fz:
        c = fz["contrasts"]
        L.append(f"| Gemma-2-9B (frozen, W_U) | {c['W_U k25 complement minus W_U k25 J-only']['diff']:+.3f} [{c['W_U k25 complement minus W_U k25 J-only']['ci95'][0]:+.3f}, {c['W_U k25 complement minus W_U k25 J-only']['ci95'][1]:+.3f}] | — | — | — | — | {-c['full minus W_U k25 complement']['diff']:+.3f} | — | — |")

    L += ["", "## 2. The three settings for the J-only probe at k = 25 (A1, A3, A2)", "",
          "| model | Core, leave-one-domain-out: full / J / complement | within Transfer, leave-one-family-out: full / J / complement (p for J) | Core → Transfer: full / J / complement (p for J) |",
          "|---|---|---|---|"]
    for m, s in res.items():
        a1 = s["A1_core_ldo"]["band_mean"][K]; a3 = s["A3_transfer_lofo"]["band_mean"][K]; a2 = s["A2_transfer"]["band_mean"][K]
        p3 = s.get("A3_inference", {}).get(K, {}).get("arms", {}).get("J", {}).get("p_perm")
        p2 = s["A2_inference"][K]["arms"]["J"]["p_perm"]
        L.append(f"| {LABEL.get(m, m)} | {f3(a1['full']['primary'])} / {f3(a1['J']['primary'])} / {f3(a1['C_J']['primary'])} | "
                 f"{f3(a3['full']['primary'])} / {f3(a3['J']['primary'])} / {f3(a3['C_J']['primary'])} (p = {p3:.3f}) | "
                 f"{f3(a2['full']['primary'])} / {f3(a2['J']['primary'])} / {f3(a2['C_J']['primary'])} (p = {p2:.3f}) |")
    if fz:
        cb = fz["core_battery_ldo"]["wu_topk k25"]
        L.append(f"| Gemma-2-9B (frozen) | 1.000 / {f3(cb['J_only'])} / {f3(cb['complement'])} | not measured | {f3(fz['transfer_arms']['full']['primary']['auroc'])} / {f3(fz['transfer_arms']['W_U k25 J-only']['primary']['auroc'])} / {f3(fz['transfer_arms']['W_U k25 complement']['primary']['auroc'])} |")

    L += ["", "## 3. Phase versus family (A4), k = 25, band mean", "",
          "| model | Core disc → Core disc (A1) | Core disc → Core final (A4a: phase changes) | Core disc → Transfer disc (A4b: family changes) | Core disc → Transfer final (A2: both) |",
          "|---|---|---|---|---|"]
    for m, s in res.items():
        def cell(key):
            bm = s.get(key, {}).get("band_mean", {}).get(K)
            return f"full {f3(bm['full']['primary'])} / J {f3(bm['J']['primary'])} / C {f3(bm['C_J']['primary'])}" if bm else "no Transfer discussion turns"
        L.append(f"| {LABEL.get(m, m)} | {cell('A1_core_ldo')} | {cell('A4a_core_disc_to_final')} | {cell('A4b_core_to_transfer_discussion')} | {cell('A2_transfer')} |")

    L += ["", "## 4. Frame size sweep, Core → Transfer (A2), band-mean primary", "",
          "| model | arm | " + " | ".join(f"k={k}" for k in res[next(iter(res))]["ks"]) + " |" if res else "", "|---|---|" + "---:|" * len(res[next(iter(res))]["ks"]) if res else ""]
    for m, s in res.items():
        for arm in ("J", "C_J", "randsub", "shuffled", "pca", "contrast"):
            L.append(f"| {LABEL.get(m, m)} | {arm} | " + " | ".join(f3(s['A2_transfer']['band_mean'][str(k)][arm]['primary']) for k in s["ks"]) + " |")
        L.append(f"| {LABEL.get(m, m)} | mean FVE of J / of random rows | " + " | ".join(f"{s['A2_transfer']['band_mean'][str(k)]['J']['fve_core']:.2f} / {s['A2_transfer']['band_mean'][str(k)]['randrows']['fve_core']:.3f}" for k in s["ks"]) + " |")

    L += ["", "## 5. Within-Transfer sweep (A3), pooled held-out primary", "",
          "| model | arm | " + " | ".join(f"k={k}" for k in res[next(iter(res))]["ks"]) + " |" if res else "", "|---|---|" + "---:|" * len(res[next(iter(res))]["ks"]) if res else ""]
    for m, s in res.items():
        for arm in ("full", "J", "C_J", "randsub", "pca"):
            L.append(f"| {LABEL.get(m, m)} | {arm} | " + " | ".join(f3(s['A3_transfer_lofo']['band_mean'][str(k)][arm]['primary']) for k in s["ks"]) + " |")

    L += ["", "## 6. Geometry at the centre layer, k = 25 (A5)", "",
          "| model | share of the full probe direction inside the frames (median) | random direction (median) | k/d | cos(full, J-only direction) | cos(full, complement direction) | Jaccard of top-100 frame tokens, colluder vs honest |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for m, s in res.items():
        g = s.get("A5_geometry")
        if g:
            L.append(f"| {LABEL.get(m, m)} | {g['share_of_full_direction_in_frames']['median']:.4f} | {g['share_of_random_direction_in_frames']['median']:.4f} | {g['k_over_d']:.4f} | "
                     f"{f3(g['cos_full_vs'].get('J'))} | {f3(g['cos_full_vs'].get('C_J'))} | {f3(g['jaccard_top100_frame_tokens_colluder_vs_honest'])} |")
    for m, s in res.items():
        g = s.get("A5_geometry")
        if g:
            L += ["", f"{LABEL.get(m, m)}, most frequent frame tokens (share of that role's Core discussion turns whose 25-token frame holds the token):", ""]
            for role, lst in g["frame_tokens_top25_by_role"].items():
                L.append(f"- {role}: " + ", ".join(f"`{t['token']!r}` {t['share_of_frames']:.2f}" for t in lst[:15]))

    L += ["", "## 7. Readings per model (rules of design section 6)", ""]
    for m, s in res.items():
        L.append(f"### {LABEL.get(m, m)}")
        L.append("")
        for key, r in s["readings"].items():
            L.append(f"- **{key}**: {r.get('reading')}")
        L.append("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(L) + "\n")
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
